def section(start_pat, end_pat=None):
    """取 start_pat 命中行到 end_pat 命中行之前的文本块。"""
    i = None
    for k, l in enumerate(lines):
        if re.search(start_pat, l):
            i = k
            break
    if i is None:
        return "（未找到：%s）" % start_pat
    j = len(lines)
    if end_pat:
        for k in range(i + 1, len(lines)):
            if re.search(end_pat, lines[k]):
                j = k
                break
    blk = [l for l in lines[i:j]]
    while blk and not blk[-1].strip():
        blk.pop()
    return "\n".join(blk)

