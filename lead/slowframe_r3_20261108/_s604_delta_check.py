# _s604_delta_check.py —— 撰写员对复核员「额外发现（表值三列内部不自洽）」的算术复核
# 问题：台账 :9706-9720 表内「空档差」列 与 「慢1/3空档 − 快1/3空档」（按显示值相减）之差 Δ，
#       能否区分「真内部矛盾」与「显示舍入伪差」？
# 判据：空档列显示 2 位小数 ⇒ 每格舍入偏差 ≤ 0.005；两列相减的伪差上限 = 0.005+0.005 = 0.010。
#       若所有 |Δ| ≤ 0.010，则「内部不自洽」不能成立（无法与显示舍入区分）；若存在 |Δ| > 0.010 才是真矛盾。
# 表值来源：撰写员本轮实读 GOAL_THREE_TARGETS_20261018.md:9706-9720（快gap, 慢gap, 空档差）。
import io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

ROWS = [
    ('l1c/w0', 2.70, 2.73,  0.032), ('l1c/w1', 2.68, 2.71,  0.028), ('l1c/w2', 2.67, 2.70,  0.030),
    ('l1d/w0', 2.66, 2.71,  0.049), ('l1d/w1', 2.65, 2.67,  0.022), ('l1d/w2', 2.64, 2.66,  0.025),
    ('l1e/w0', 2.65, 2.65,  0.003), ('l1e/w1', 2.63, 2.66,  0.035), ('l1e/w2', 2.63, 2.64,  0.018),
    ('l3/w0',  2.75, 2.75, -0.002), ('l3/w1',  2.68, 2.72,  0.037), ('l3/w2',  2.71, 2.71,  0.002),
    ('t55k/w0', 2.62, 2.60, -0.013), ('t55k/w1', 2.61, 2.60, -0.006), ('t55k/w2', 2.61, 2.61, -0.000),
]
BOUND = 0.005 + 0.005
print(f'舍入伪差上限 BOUND = {BOUND:.4f} ms')
mx = 0.0
over = 0
for name, fg, sg, d in ROWS:
    delta = d - (sg - fg)
    flag = '超界' if abs(delta) > BOUND else '舍入可解释'
    if abs(delta) > BOUND:
        over += 1
    mx = max(mx, abs(delta))
    print(f'{name:8s} 空档差列 {d:+.3f}  显示值算术差 {sg - fg:+.3f}  Δ = {delta:+.4f}  |Δ|={abs(delta):.4f}  {flag}')
print(f'最大 |Δ| = {mx:.4f} ms；|Δ|>0.010 的格数 = {over}/15')
print('结论：' + ('存在 |Δ|>0.010 ⇒ 表值三列内部矛盾成立' if over else '全部 |Δ|≤0.010 ⇒ 「三列内部不自洽」不能成立（均可由空档列 2 位显示舍入解释），不能作为独立矛盾引用'))
print('== END ==')
