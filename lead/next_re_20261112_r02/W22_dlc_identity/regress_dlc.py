def _norm_game_path(text: str, *game_dirs: Path) -> str:
    """C1/C2 compare the v0.5 reference output against the v0.6 output; the
    only expected difference is the game-directory PATH printed in the CLI
    header ('uninstalled from <dir>:'). Normalise those paths away before the
    byte-identity comparison - everything else must match exactly."""
    for gd in game_dirs:
        text = text.replace(str(gd), "<GAME_DIR>")
    return text


