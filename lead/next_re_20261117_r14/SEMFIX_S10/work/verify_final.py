def values(entry):
    """return set of int values present: instruction addresses + all numeric operands/displacements"""
    s=set()
    for i in D.get(entry,[]):
        s.add(int(i["a"],16))            # instruction address (8-digit form)
        for m in re.finditer(r'0x[0-9a-fA-F]+', i["m"]+" "+i["o"]):
            s.add(int(m.group(0),16))
        # decimal displacements in [reg + N] / [reg*scale + N]
        for m in re.finditer(r'\+\s*(\d+)\]', i["o"]):
            s.add(int(m.group(1),10))
    return s

