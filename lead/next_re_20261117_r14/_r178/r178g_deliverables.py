PASS = FAIL = 0


def ck(n, c, d=''):
    global PASS, FAIL
    if c:
        PASS += 1; print('PASS %s  %s' % (n, d))
    else:
        FAIL += 1; print('FAIL %s  %s' % (n, d))


def load(p):
    b = open(p, 'rb').read()
    return b, b.decode('utf-8')


DRY = '--dry' in sys.argv


def commit(p, tag, txt, newtxt, want_cr):
    """旧 sha/CR 断言 -> wx 备份 -> 写 -> 回读校验。

    DRY 模式下只跑断言，不落盘（用于四件套全量预演；任一 FAIL 即中止）。
    """
    raw, old = load(p)
    ck('%s CR 现状 = %d' % (tag, want_cr), raw.count(b'\r') == want_cr, raw.count(b'\r'))
    ck('%s 新内容前缀保留旧内容' % tag, newtxt.startswith(old))
    ck('%s 新内容 CR 仍 = %d' % (tag, want_cr), newtxt.count('\r') == want_cr, newtxt.count('\r'))
    # R14_COMMON 历史上已含 43 个 NUL（形如 0x00 的转义残留，见首现处 'x47C427'），
    # 故断言不能写「无 NUL」，必须写「NUL 数不增」——否则是恒假断言。
    ck('%s 新内容 NUL 数不增（旧 %d → 新 %d）' % (tag, old.count('\x00'), newtxt.count('\x00')),
       newtxt.count('\x00') == old.count('\x00'),
       (old.count('\x00'), newtxt.count('\x00')))
    if DRY:
        ck('%s DRY 未写盘' % tag, True)
        return raw, newtxt.encode('utf-8')
    bak = os.path.join(BASE, '%s.before_r178.bak' % tag)
    if os.path.exists(bak):
        ck('%s 备份不应已存在（本轮只跑一次）' % tag, False, bak)
    else:
        with open(bak, 'xb') as f:
            f.write(raw)
        ck('%s 备份 sha == 现盘前态' % tag,
           hashlib.sha256(open(bak, 'rb').read()).hexdigest() == hashlib.sha256(raw).hexdigest())
    open(p, 'w', encoding='utf-8', newline='').write(newtxt)
    back, btxt = load(p)
    ck('%s 回读逐字一致' % tag, btxt == newtxt)
    ck('%s 回读 CR 仍 = %d' % (tag, want_cr), back.count(b'\r') == want_cr, back.count(b'\r'))
    return raw, back


