fails, buf = [], []
def W(s=''): print(s); buf.append(s)
def ck(n, c, d=''):
    W(('  PASS ' if c else '  FAIL ') + n + (('  ' + str(d)) if d else ''))
    if not c: fails.append(n)

ts = time.strftime('%Y%m%d_%H%M%S')

def append_block(path, label, block, exp_cr, expect_lines_eq=None, arch=None):
    """按写入纪律追加。block 必须为 str，末尾自带换行。"""
    raw = open(path, 'rb').read()
    old_sha = hashlib.sha256(raw).hexdigest()
    old_cr = raw.count(b'\r'); old_lf = raw.count(b'\n')
    W('')
    W('--- %s ---' % label)
    W('  [before] %d B  CR=%d  LF=%d  sha=%s' % (len(raw), old_cr, old_lf, old_sha[:16]))
    ck('%s 旧 CR == %d' % (label, exp_cr), old_cr == exp_cr, old_cr)
    b = block.encode('utf-8')
    ck('%s 新块全 LF（无 CR）' % label, b.count(b'\r') == 0, b.count(b'\r'))
    ck('%s 旧文件以换行结尾（追加不粘连）' % label, raw.endswith(b'\n'), raw[-1:])
    nb = raw + b
    new_cr = nb.count(b'\r')
    ck('%s 新文件 CR 仍 == %d' % (label, exp_cr), new_cr == exp_cr, new_cr)
    if not DRY:
        bk = os.path.join(BASE, 'SUPERSEDED.before_r70_%s_%s%s'
                          % (label.replace('.md', '').replace(' ', ''), ts,
                             '.md' if path.endswith('.md') else '.txt'))
        with open(bk, 'xb') as f:      # wx 独占
            f.write(raw)
        ck('%s 备份回读字节一致' % label, open(bk, 'rb').read() == raw)
        ck('%s 备份 sha == 旧 sha' % label,
           hashlib.sha256(open(bk, 'rb').read()).hexdigest() == old_sha)
        with open(path, 'wb') as f:
            f.write(nb)
        back = open(path, 'rb').read()
        ck('%s 回读字节 == 预期' % label, back == nb)
        ck('%s 回读 CR == %d' % (label, exp_cr), back.count(b'\r') == exp_cr, back.count(b'\r'))
        ck('%s 回读 sha == 预期' % label, hashlib.sha256(back).hexdigest() == hashlib.sha256(nb).hexdigest())
        W('  [after]  %d B  CR=%d  LF=%d  sha=%s  (+%d B)'
          % (len(back), back.count(b'\r'), back.count(b'\n'),
             hashlib.sha256(back).hexdigest()[:16], len(nb) - len(raw)))
        if expect_lines_eq is not None:
            ck('%s 行数 == %d' % (label, expect_lines_eq),
               back.count(b'\n') == expect_lines_eq, back.count(b'\n'))
        if arch:
            ck('%s 归档 CR 仍 %d' % (label, arch[1]),
               open(arch[0], 'rb').read().count(b'\r') == arch[1])
    return nb

