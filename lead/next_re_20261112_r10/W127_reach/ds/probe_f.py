from base import BUF, IB, u32, cstr, in_raw, blob
td = 0x00816C70
raw = blob(td, 0x18)
print("=== byte-exact TypeDescriptor at VA 0x%08X ===" % td)
print("  raw[0:0x14] =", raw[:0x14].hex())
print("  as chars   =", repr(raw[:0x14]))
print()
for off in range(0, 0x18, 4):
    print("  TD+0x%02X = %08X" % (off, u32(td + off)))
print()
print("  >>> the string '.?AVScrollClass@@' starts at TD+0x08 (%08X)" % (td + 8))
print("      bytes: %r" % raw[8:8+20])
print("  >>> u32(TD+0x08) = %08X is NOT a pointer; it is the first 4 chars '\\x2e\\x3f\\x41\\x56'")
print()
print("=== MSVC RTTI reading: the stored FOUR bytes are the LENGTH+PAD, then chars ===")
sig = u32(td + 8)
print("  reinterpret: first dword after spare = %08X  (char bytes: %s)" % (sig, raw[8:12].hex()))
print()
print("=== CHAIN with the ACTUAL layout ===")
print("   vt        = 007F1094")
print("   [vt-4]    = %08X   (COL)" % u32(0x007F1090))
print("   COL+0x0C  = %08X   (pTypeDescriptor)" % u32(0x00809060 + 0xC))
print("   TD+0x00   = %08X   (type_info vftable, .rdata)" % u32(td))
print("   TD+0x08   = inline name bytes %r" % raw[8:28])
print()
print("  So in THIS build, the TypeDescriptor is:")
print("    +0x00 vftable ptr (0x7F9594)")
print("    +0x04 spare     (0)")
print("    +0x08 NAME STRING INLINE ('.?AVScrollClass@@')")
print("  i.e. the name is an INSIDE-THE-STRUCT char array, not a pointer.")
print("  The task recipe said 'TD+0x08 is the name' -- reading it as a POINTER")
print("  is wrong; reading it as the first 4 chars of an inline array is right.")
