#!/usr/bin/env python3
"""W128h: generate + verify the null-safe replacements for the 3 sites of the
third defect (FUN_006f3f40, ledger §831/§837).

Each site is exactly 12 bytes:
    0x6F409C  mov edx,[ecx+0xAC]   (6)   mov al,[edx+0x155]  (6)
    0x6F4124  mov edx,[ecx+0xAC]   (6)   mov al,[edx+0x159]  (6)
    0x6F4173  mov ecx,[eax+0xAC]   (6)   mov al,[ecx+0x15A]  (6)
and each is followed by `test al,al`. So the 12 bytes can be replaced by
`call <helper>` (5) + 7 x NOP, with one helper per site.

Helper (site1 example, obj in ECX, dst in EDX):
    mov edx,[ecx+0xAC]
    test edx,edx
    jz  .null
    mov al,[edx+0x155]
    ret
  .null:
    xor al,al
    ret
Semantics preserved: same registers loaded, same AL result; only the would-be
crash case changes (AL=0 => the caller's `je` skips the block).

Nothing else may be clobbered: helpers touch only the original dst reg + AL,
and a `call` is transparent because no site depends on ESP across the 12 bytes.
"""
import json
import os

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "sites_generated.h")
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)

# (site_va, obj_reg_is_ecx, dst_is_edx, offset, site_len)
SITES = [
    ("0x006F409C", True,  True,  0x155, 12),
    ("0x006F4124", True,  True,  0x159, 12),
    ("0x006F4173", False, False, 0x15A, 12),   # obj in EAX, dst in ECX
]

def mov_reg_mem(dst_reg, base_reg, disp):
    """emit `mov dst,[base+disp32]`  (ModRM 10 /r)"""
    # opcode 8B, mod=10, reg=dst, rm=base
    return bytes([0x8B, 0x80 | (dst_reg << 3) | base_reg]) + disp.to_bytes(4, "little")

def mov_al_mem(base_reg, disp):
    """emit `mov al,[base+disp32]`  (opcode 8A, mod=10, reg=0(AL), rm=base)"""
    return bytes([0x8A, 0x80 | (0 << 3) | base_reg]) + disp.to_bytes(4, "little")

ECX, EDX, EAX = 1, 2, 0
TEST = {EDX: bytes([0x85, 0xD2]), ECX: bytes([0x85, 0xC9])}
XOR_AL_AL = bytes([0x30, 0xC0])
RET = bytes([0xC3])
JZ_SHORT = 0x74

helpers = []
for site, obj_is_ecx, dst_is_edx, off, slen in SITES:
    obj = ECX if obj_is_ecx else EAX
    dst = EDX if dst_is_edx else ECX
    code = bytearray()
    code += mov_reg_mem(dst, obj, 0xAC)
    code += TEST[dst]
    code += bytes([JZ_SHORT, 0])          # placeholder
    jz_pos = len(code) - 1
    code += mov_al_mem(dst, off)
    code += RET
    null_at = len(code)
    code += XOR_AL_AL
    code += RET
    rel8 = null_at - (jz_pos + 1)
    assert -128 <= rel8 <= 127, (site, rel8)
    code[jz_pos] = rel8 & 0xFF

    # verify
    insns = [(i.address, i.bytes.hex(), i.mnemonic, i.op_str)
             for i in md.disasm(bytes(code), 0)]
    print("\n=== helper for site %s  (obj=%s dst=%s off=0x%X)  len=%d"
          % (site, "ecx" if obj_is_ecx else "eax", "edx" if dst_is_edx else "ecx",
             off, len(code)))
    for a, b, m, o in insns:
        print("   +%02X  %-20s %s %s" % (a, b, m, o))
    print("   jz lands on +%02X (null path)" % null_at)

    helpers.append({"site": site, "bytes": code.hex(), "len": len(code),
                    "obj_is_ecx": obj_is_ecx, "off": off})

lines = ["/* AUTO-GENERATED by site_gen.py -- null-safe helpers for the 3 sites of",
         " * FUN_006f3f40 (third defect). Patch each site with",
         " *   E9/FF-call? -> no:  E8 rel32 <helper>  + 7 x 0x90",
         " * (site is exactly 12 bytes, ends right before `test al,al`).",
         " */",
         "#ifndef SITES_GENERATED_H",
         "#define SITES_GENERATED_H",
         ""]
for h in helpers:
    name = "helper_%s" % h["site"][2:]
    bs = ", ".join("0x%s" % h["bytes"][i:i + 2] for i in range(0, len(h["bytes"]), 2))
    lines.append("/* site %s  obj=%s  len=%d */"
                 % (h["site"], "ecx" if h["obj_is_ecx"] else "eax", h["len"]))
    lines.append("static const unsigned char %s[%d] = { %s };"
                 % (name, h["len"], bs))
    lines.append("")
lines.append("#endif")
open(OUT, "w").write("\n".join(lines))
json.dump(helpers, open(os.path.join(HERE, "sites.json"), "w"), indent=2)
print("\nwrote", OUT)
