#!/usr/bin/env python3
"""W128b: hand-assemble the 6 null-guard stubs, VERIFY them with capstone,
then emit C byte arrays. No C toolchain needed on this machine.

Stub shape (compiler- and assembler-independent):

    test ecx,ecx          85 C9
    jz   short <null>     74 xx
    <relocated original bytes, verbatim>
    jmp  rel32 <resume>   E9 00 00 00 00      (rel32 patched at install time)
  null:
    [xor eax,eax]         31 C0                (only if the fn returns a value)
    ret  imm16            C2 ii 00   |  C3     (matches the original epilogue)

Why bytes instead of inline asm: MSVC `__asm` is Intel syntax while GCC's is
AT&T; a single source cannot be correct for both, and this machine has neither
32-bit compiler, so nothing could be checked. Byte arrays can be verified here.
"""
import json
import os

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
ENTRIES = os.path.join(HERE, "entries.json")
OUT_H = os.path.join(HERE, "stubs_generated.h")

data = json.load(open(ENTRIES))
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)

TEST_ECX = [0x85, 0xC9]
JZ_SHORT = 0x74
XOR_EAX = [0x31, 0xC0]
JMP_REL32 = 0xE9

stubs = []

for e in data["entries"]:
    fn = e["fn"]
    reloc = bytes.fromhex(e["relocate_bytes"])
    resume = int(e["resume_at"], 16)
    pop = e["pop_bytes"]
    want_al = e["returns_al"]

    code = bytearray()
    code += bytes(TEST_ECX)
    code += bytes([JZ_SHORT, 0x00])          # placeholder offset
    jz_pos = len(code) - 1                   # index of the rel8
    code += reloc                            # relocated original bytes
    jmp_pos = len(code)
    code += bytes([JMP_REL32, 0, 0, 0, 0])   # jmp rel32 -> patched later
    null_pos = len(code)
    if want_al:
        code += bytes(XOR_EAX)
    if pop:
        code += bytes([0xC2, pop & 0xFF, 0x00])
    else:
        code += bytes([0xC3])

    # fix jz rel8: target null_pos, relative to end of the jz instruction
    rel8 = null_pos - (jz_pos + 1)
    assert -128 <= rel8 <= 127, (fn, rel8)
    code[jz_pos] = rel8 & 0xFF

    # ---- verify by disassembling with capstone ----
    insns = []
    for ins in md.disasm(bytes(code), 0):
        insns.append((ins.address, ins.bytes.hex(), ins.mnemonic, ins.op_str))
    print("\n=== %s  relocate=%d  pop=%d  returns_al=%d  stub_len=%d"
          % (fn, len(reloc), pop, want_al, len(code)))
    for addr, b, m, o in insns:
        print("   +%02X  %-20s %s %s   (%s)" % (addr, b, m, o,
              "RELOC" if b in reloc.hex() and 0 else ""))
    print("   -> jz lands on +%02X, null path starts at +%02X, resume=0x%08X"
          % (null_pos, null_pos, resume))

    stubs.append({
        "fn": fn, "bytes": code.hex(), "len": len(code),
        "jmp_rel32_off": jmp_pos + 1,      # offset of the disp32 inside the stub
        "null_off": null_pos, "resume": resume,
        "pop": pop, "returns_al": want_al,
    })

# ---- emit header ----
lines = ["/* AUTO-GENERATED by stub_gen.py -- do not edit by hand.",
         " * Each stub: test ecx,ecx / jz null / <relocated original bytes> /",
         " *             jmp rel32 <resume> / null: [xor eax,eax] ret imm",
         " * The disp32 of the final `jmp` is zero here and patched at install time",
         " * at offset `jmp_rel32_off`.",
         " */",
         "#ifndef STUBS_GENERATED_H",
         "#define STUBS_GENERATED_H",
         ""]
for s in stubs:
    name = "stub_%s" % s["fn"][2:]
    bs = ", ".join("0x%s" % s["bytes"][i:i + 2] for i in range(0, len(s["bytes"]), 2))
    lines.append("/* %s  len=%d  resume=0x%08X  jmp_disp_off=%d  pop=%d  ret_al=%d */"
                 % (s["fn"] if False else s["fn"], s["len"], s["resume"],
                    s["jmp_rel32_off"], s["pop"], s["returns_al"]))
    lines.append("static const unsigned char %s[%d] = { %s };"
                 % (name, s["len"], bs))
    lines.append("")
lines.append("#endif")

open(OUT_H, "w").write("\n".join(lines))
print("\nwrote", OUT_H)
json.dump(stubs, open(os.path.join(HERE, "stubs.json"), "w"), indent=2)
