def audit(path, exp_cr, tag, append_bytes):
    b0 = open(path, 'rb').read()
    ck('%s 写入前 CR == %d' % (tag, exp_cr), b0.count(b'\r') == exp_cr, b0.count(b'\r'))
    b = os.path.join(BASE, '%s.before_R148_%s_%s.bak' % (os.path.basename(path), tag, TS))
    fd = os.open(b, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    with os.fdopen(fd, 'wb') as f:
        f.write(b0)
    ck('%s 备份 wx 且逐字节相同' % tag, open(b, 'rb').read() == b0, os.path.basename(b))
    ck('%s 追加段不含 CR' % tag, b'\r' not in append_bytes, append_bytes.count(b'\r'))
    b1 = b0 + append_bytes
    with open(path, 'wb') as f:
        f.write(b1)
    b2 = open(path, 'rb').read()
    ck('%s 回读逐字节相同' % tag, b2 == b1)
    ck('%s 写入后 CR 仍 == %d' % (tag, exp_cr), b2.count(b'\r') == exp_cr, b2.count(b'\r'))
    ck('%s 字节增加 == 追加长度' % tag, len(b2) - len(b0) == len(append_bytes),
       (len(b0), len(b2), len(append_bytes)))
    return len(b0), len(b2), b


