fails=[]
def ck(n,c,d=''):
    ok=bool(c); print(('  PASS ' if ok else '  FAIL ')+n+(('  '+str(d)) if d else ''))
    if not ok: fails.append(n)
    return ok
def sha(p): return hashlib.sha256(open(p,'rb').read()).hexdigest()
def crc(p): return open(p,'rb').read().count(b'\r')
def backup(p):
    b=os.path.join(BASE, os.path.basename(p)+'.before_'+TAG+'.bak')
    fd=os.open(b,os.O_CREAT|os.O_EXCL|os.O_WRONLY,0o644)
    with os.fdopen(fd,'wb') as f: f.write(open(p,'rb').read())
    return b
def append(p, text, expect_cr, expect_old_sha=None):
    old_sha=sha(p); old_cr=crc(p); old_n=open(p,'rb').read().count(b'\n')
    if expect_old_sha is not None:
        ck('旧 sha 断言 %s'%os.path.basename(p), old_sha.startswith(expect_old_sha), old_sha[:16])
    b=backup(p)
    ck('备份 wx 独占 %s'%os.path.basename(p), os.path.exists(b))
    ck('备份字节=源 %s'%os.path.basename(p), sha(b)==old_sha)
    assert b'\r' not in text.encode('utf-8')
    with open(p,'ab') as f: f.write(text.encode('utf-8'))
    ck('CR 保持 %d (%s)'%(expect_cr,os.path.basename(p)), crc(p)==expect_cr, crc(p))
    new_n=open(p,'rb').read().count(b'\n')
    ck('行数只增 %s'%os.path.basename(p), new_n>old_n, '%d->%d'%(old_n,new_n))
    ck('前缀 sha 等于旧 sha %s'%os.path.basename(p),
       hashlib.sha256(open(p,'rb').read()[:os.path.getsize(b)]).hexdigest()==old_sha)
    return old_sha

