MARK = 'R137'


def sha(b):
    return hashlib.sha256(b).hexdigest()


def backup(p):
    """wx 独占创建，已存在即失败 —— 保证备份唯一、不被覆盖。"""
    data = io.open(p, 'rb').read()
    stamp = time.strftime('%Y%m%d_%H%M%S')
    dst = os.path.join(BASELINE, '%s.before_R137_%s.bak' % (os.path.basename(p), stamp))
    fd = os.open(dst, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    with os.fdopen(fd, 'wb') as f:
        f.write(data)
    assert io.open(dst, 'rb').read() == data, 'backup content mismatch'
    print('backup  %-24s %d B  %s' % (os.path.basename(p), len(data), os.path.basename(dst)))
    return dst


def precheck():
    ok = True
    for p, (want_sha, want_cr) in PRE.items():
        b = io.open(p, 'rb').read()
        got_sha, got_cr = sha(b), b.count(b'\r')
        if got_sha != want_sha:
            print('ABORT sha mismatch on %s: %s != %s' % (p, got_sha[:16], want_sha[:16]))
            ok = False
        if got_cr != want_cr:
            print('ABORT CR mismatch on %s: %d != %d' % (p, got_cr, want_cr))
            ok = False
        if MARK.encode() in b[-400000:]:
            print('ABORT %s already contains marker %s in tail' % (os.path.basename(p), MARK))
            ok = False
    return ok


def app(p, txt, want_cr):
    if not txt.endswith('\n'):
        txt = txt + '\n'
    assert '\r' not in txt, 'text contains CR; refusing'
    before = io.open(p, 'rb').read()
    assert before.count(b'\r') == want_cr, 'CR drifted before write on ' + p
    with io.open(p, 'ab') as f:                 # 二进制追加，绝不重写既有字节
        f.write(txt.encode('utf-8'))
    after = io.open(p, 'rb').read()
    assert after.count(b'\r') == want_cr, 'CR changed on ' + p
    assert after.startswith(before), 'file not appended cleanly on ' + p
    assert len(after) > len(before), 'no bytes added on ' + p
    print('  wrote %-24s +%d B  CR %d  LF %d  total %d B  sha %s'
          % (os.path.basename(p), len(after) - len(before), after.count(b'\r'),
             after.count(b'\n'), len(after), sha(after)[:16]))
    return after


