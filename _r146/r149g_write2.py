    new=open(p,'rb').read()
    ck(label+' CR 保持 '+str(expect_cr), crc(p)==expect_cr, crc(p))
    ck(label+' 仅追加', len(new)>len(old))
    ck(label+' 前缀 sha 未变', hashlib.sha256(new[:len(old)]).hexdigest()==old_sha)

