def crc(p): return open(p,'rb').read().count(b'\r')

def append(p, text, expect_cr, label):
    old=open(p,'rb').read(); old_sha=hashlib.sha256(old).hexdigest()
    b=os.path.join(BASE, os.path.basename(p)+'.before_'+TAG+'.bak')
