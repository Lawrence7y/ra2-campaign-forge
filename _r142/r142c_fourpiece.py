cc, cc_n = [], 0
log = []


def ck(name, cond, detail=''):
    global cc_n
    cc_n += 1
    print(('  PASS ' if cond else '  FAIL ') + name + (('  ' + str(detail)) if detail else ''))
    if not cond:
        cc.append(name)


def sha(b):
    return hashlib.sha256(b).hexdigest()


def stats(b):
    return dict(cr=b.count(b'\r'), lf=b.count(b'\n'), bytes=len(b), sha=sha(b))


def backup(path, tag):
    b = open(path, 'rb').read()
    st = stats(b)
    name = '%s.before_%s_%s.bak' % (os.path.basename(path), tag,
                                    time.strftime('%Y%m%d_%H%M%S'))
    dst = os.path.join(BL, name)
    # wx 独占创建：已存在则抛 FileExistsError
    with io.open(dst, 'xb') as f:
        f.write(b)
    rb = open(dst, 'rb').read()
    ck('[%s] 备份 wx 独占创建且内容逐字节相同' % tag, rb == b, dst)
    ck('[%s] 备份 sha 与源一致' % tag, sha(rb) == st['sha'], st['sha'][:8])
    log.append(dict(file=os.path.basename(path), backup=dst, before=st))
    return st


def append(path, text, tag):
    old = open(path, 'rb').read()
    before = stats(old)
    backup(path, tag)
    data = old + text.encode('utf-8')
    with io.open(path, 'wb') as f:
        f.write(data)
    back = open(path, 'rb').read()
    after = stats(back)
    ck('[%s] 回读 == 期望写入内容' % tag, back == data)
    ck('[%s] 回读 sha 与期望一致' % tag, sha(back) == sha(data), sha(back)[:8])
    ck('[%s] 旧内容是新内容的前缀（纯追加）' % tag, back.startswith(old))
    log[-1]['after'] = after
    return before, after


