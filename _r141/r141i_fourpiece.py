TS = time.strftime('%Y%m%d_%H%M%S')
fails = []


def ck(name, cond, detail=''):
    print(('  PASS ' if cond else '  FAIL ') + name + (('  ' + str(detail)) if detail else ''))
    if not cond:
        fails.append(name)


def backup(path, tag):
    b = os.path.join(BASE, '%s.before_R141_%s_%s.bak' % (os.path.basename(path), tag, TS))
    d = open(path, 'rb').read()
    fd = os.open(b, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    with os.fdopen(fd, 'wb') as f:
        f.write(d)
    ck('备份 wx 创建 %s' % os.path.basename(b), os.path.exists(b))
    ck('备份逐字节相同 %s' % tag, open(b, 'rb').read() == d)
    return b, d


def cr(b):
    return b.count(b'\r')


def audit(path, exp_cr, tag, append_bytes, must_lf=True):
    b0 = open(path, 'rb').read()
    ck('%s 写入前 CR == %d' % (tag, exp_cr), cr(b0) == exp_cr, cr(b0))
    bak, _ = backup(path, tag)
    b1 = b0 + append_bytes
    with open(path, 'wb') as f:
        f.write(b1)
    b2 = open(path, 'rb').read()
    ck('%s 回读逐字节相同' % tag, b2 == b1)
    ck('%s 写入后 CR 仍 == %d' % (tag, exp_cr), cr(b2) == exp_cr, cr(b2))
    if must_lf:
        ck('%s 追加段不含 \\r' % tag, b'\r' not in append_bytes, append_bytes.count(b'\r'))
    ck('%s 字节增加 == 追加段长度' % tag, len(b2) - len(b0) == len(append_bytes),
       (len(b0), len(b2), len(append_bytes)))
    return len(b0), len(b2), bak


